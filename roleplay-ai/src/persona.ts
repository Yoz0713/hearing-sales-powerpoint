/**
 * 系統提示的最後一行：只在「該守住核心顧慮」的那一個回合出現。
 * 禁字規則本來只寫在 statusOf 裡，中間隔了一整段人設與評估準則就被稀釋掉，
 * 模型常在第一次一般探索就把「戴出去怪怪的」講破，兩段式揭露的節奏整個沒了。
 */
function finalGuardOf(state: GateState, stage: Stage): string {
  if (stage !== 'closed' || !state.lifeContext || state.concernProbeCount > 0) return '';
  return '【最後提醒】這一回合的 reply 絕對不能出現「戴出去」「怪怪的」「朋友看到」「顯老」「不中用」「外觀」這幾個字，也不能換句話暗示同樣的意思。除非對方這一則直接問到外觀或身份，否則核心顧慮這一回合要守住。';
}

/** 依目前累積關卡狀態組出「目前狀態」段落，讓模型正確決定這一則該怎麼演。 */
function statusOf(state: GateState, stage: Stage): string {
  switch (stage) {
    case 'accepted':
      return '【目前狀態】你已經答應對方的邀約了。接下來語氣輕鬆、收尾即可，不要再提出新的要求。';
    case 'ready':
      return '【目前狀態】你已經鬆口，而且擔心也被好好回應了（階段三）。你心裡已經願意了，但**絕不能自己提下一步**，只能等對方開口邀請；他一開口你就答應。';
    case 'open':
      return '【目前狀態】你已明確說出怕助聽器被朋友看到、顯老或被認為不中用（階段二）。對方還沒具體接住這個身份焦慮，所以還不到願意的程度。';
    default:
      if (!state.lifeContext) {
        return '【目前狀態】你還沒鬆口（階段一）。生活情境還沒被好好問到；先守住所有核心顧慮，就算對方直接猜外觀也不要正式承認。';
      }
      if (state.concernProbeCount === 0) {
        return '【目前狀態】生活痛點已問到，但核心外觀／標籤焦慮尚未揭露，有效探索次數＝0。若最新一則直接探索身份焦慮就明確說出；若只是第一次一般探索，只能回答效果、過去經驗或其他表層內容。這一回合 reply 禁止出現「戴出去」「怪怪的」「朋友看到」「顯老」「不中用」「外觀」，絕不能提前給提示。';
      }
      if (state.concernProbeCount === 1) {
        return '【目前狀態】生活痛點已問到，核心外觀／標籤焦慮尚未揭露，有效探索次數＝1。若最新一則直接探索身份焦慮就明確說出；若又是一般有效探索，這次只給「戴那個出去總覺得怪怪的」之類的含蓄提示，不把答案講破。';
      }
      return '【目前狀態】生活痛點已問到，而且你已給過外觀方向的含蓄提示，但核心顧慮尚未明說。只有對方直接探索外觀／身份，或有意義地追問那個提示時，才明確說出怕被朋友看到、顯老或被認為不中用。';
  }
}

/** 依目前累積關卡狀態組出單一系統提示（含即時狀態，讓模型正確決定鬆口與答應與否）。 */
export function buildSystemPrompt(state: GateState): string {
  const stage = stageOf(state);
  return [
    CHARACTER,
    HIDDEN_TRUTH,
    CLOSED_BEHAVIOR,
    OPEN_BEHAVIOR,
    READY_BEHAVIOR,
    UNUSUAL_INPUT_BEHAVIOR,
    NEVER_INITIATE,
    INVITE_RULES,
    DISCLOSURE_RULES,
    RULES,
    statusOf(state, stage),
    EVALUATOR,
    OUTPUT,
    finalGuardOf(state, stage),
  ]
    .filter(Boolean)
    .join('\n\n');
}

