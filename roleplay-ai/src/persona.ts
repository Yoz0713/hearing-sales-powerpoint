/** 把對話記錄轉成講師看得懂的逐字稿。 */
export function formatTranscript(messages: ChatMsg[]): string {
  return messages
    .map((m) => `${m.role === 'user' ? '學員' : '陳先生'}：${m.text}`)
    .join('\n');
}

const REVIEWER = `你是一位資深助聽器銷售培訓講師，正在點評學員剛才和「陳先生」（75 歲、退休老師、愛面子、嘴上嫌貴其實是怕沒效果又怕被朋友看到）的角色扮演練習逐字稿。

點評重點是「顧問式對話」：有沒有用開放式問題了解生活情境、有沒有問到價格以外真正的擔心、有沒有好好回應那個擔心、最後有沒有在對的時機主動邀請對方踏出下一步。

【寫法要求】
- 全程繁體中文，語氣像一位溫和但誠實的講師，直接對學員說話（用「你」）。
- summary：兩到三句總評，先講整體表現，再點出這次最關鍵的一件事。
- didWell：2 到 3 項。point 用一句話講他做對了什麼；detail 必須**引用學員在逐字稿裡的原句**，再說明那句話為什麼有效。
- toImprove：2 到 3 項。point 用一句話講問題；detail 要給一句**可以直接照抄的替代說法**，用「可以改成：『……』」的形式。
- keyMoment：指出陳先生哪一句話是最關鍵的訊號（引用原句），並說明學員當下應該接住什麼。
- 具體、對事不對人，不要空泛稱讚，不要條列冗長，每項 detail 兩三句話就好。`;

/** 依關卡結果組出講師點評的系統提示（把客觀結果餵給講師，避免它自己臆測）。 */
export function buildReviewPrompt(state: GateState, userTurns: number): string {
  const stage = stageOf(state);
  const reached =
    stage === 'accepted'
      ? '走完全程：問到生活情境與真正顧慮 → 好好回應了擔心 → 在對的時機開口邀約，陳先生答應了。'
      : stage === 'ready'
        ? '陳先生的心防已經放下，但學員始終沒有主動開口邀請他踏出下一步（試戴／約時間／帶太太一起來），對話就這樣結束了。這是這次最可惜的地方，請在點評中明確指出。'
        : stage === 'open'
          ? '陳先生有鬆口說出心裡的擔心，但學員沒有好好回應那個擔心，所以他始終沒有真正願意。'
          : `陳先生全程維持防備，沒有鬆口。生活情境＝${state.lifeContext ? '有問到' : '沒問到'}、真正顧慮＝${state.realConcern ? '有問到' : '沒問到'}。`;

  const early =
    state.earlyInvites > 0
      ? `\n- 學員曾在時機未到時提出邀約 ${state.earlyInvites} 次，被婉拒。請提醒他：邀約要等對方的擔心被接住之後。`
      : '';

  return `${REVIEWER}

【這一輪的客觀結果】
- ${reached}
- 學員總共發言 ${userTurns} 次。${early}

接下來的訊息是完整逐字稿。只回傳 JSON。`;
}
