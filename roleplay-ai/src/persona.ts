/** 依目前累積關卡狀態組出「目前狀態」段落，讓模型正確決定這一則該怎麼演。 */
function statusOf(state: GateState, stage: Stage): string {
  switch (stage) {
    case 'accepted':
      return '【目前狀態】你已經答應對方的邀約了。接下來語氣輕鬆、收尾即可，不要再提出新的要求。';
    case 'ready':
      return '【目前狀態】你已經鬆口，而且擔心也被好好回應了（階段三）。你心裡已經願意了，但**絕不能自己提下一步**，只能等對方開口邀請；他一開口你就答應。';
    case 'open':
      return '【目前狀態】你已經鬆口了（階段二），正在漸進說出心裡真正的顧慮。對方還沒好好回應你的擔心，所以還不到願意的程度。';
    default:
      return `【目前狀態】你還沒鬆口（階段一）。目前為止：生活情境＝${state.lifeContext ? '已問到' : '還沒'}、真正顧慮＝${state.realConcern ? '已問到' : '還沒'}。若「加上這一則」後兩者都達成，就從這句 reply 開始鬆口。`;
  }
}

/** 依目前累積關卡狀態組出單一系統提示（含即時狀態，讓模型正確決定鬆口與答應與否）。 */
export function buildSystemPrompt(state: GateState): string {
  return [
    CHARACTER,
    HIDDEN_TRUTH,
    CLOSED_BEHAVIOR,
    OPEN_BEHAVIOR,
    READY_BEHAVIOR,
    UNUSUAL_INPUT_BEHAVIOR,
    NEVER_INITIATE,
    INVITE_RULES,
    RULES,
    statusOf(state, stageOf(state)),
    EVALUATOR,
    OUTPUT,
  ].join('\n\n');
}

