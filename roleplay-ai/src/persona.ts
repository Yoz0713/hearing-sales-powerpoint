const OUTPUT = `【輸出】只回傳 JSON：依 schema 先給九個布林判斷，最後 reply 放陳先生要說的那一句話（口語、簡短、一次一句）。identityConcernDisclosed 與 acceptedInvite 必須和 reply 的實際內容一致 —— reply 在婉拒就不能給 acceptedInvite=true，reply 答應了就不能給 false。其餘判斷與目前階段也必須一致。
【送出前的回頭自檢】把 reply 寫完之後，照它的實際意思再確認這兩格：
- identityConcernDisclosed 的判準是**有沒有第三人稱的眼光** —— 你怕的是「別人怎麼看我」，不是「我老了」這件事本身。reply 要出現「別人／朋友／人家看到我戴、會怎麼想我」這層意思才給 true，例如「被朋友看到，好像就承認自己老了」「人家會覺得我不中用」（不論是主動說的還是順著對方的話承認的）。
  · 這些一律 false：單純感嘆自己年紀（「人老了就是這樣啦」「我這年紀了」「老毛病了」）、只講身體或效果（「聽不清楚」「戴了也沒用」）、含蓄帶過（「戴出去怪怪的」）、學員猜了但你沒承認。
  · 關鍵差別是**有沒有講到別人怎麼看你**，不是有沒有出現「老」這個字。
- reply 若答應了下一步（「那…好吧」「我就先戴看看」），acceptedInvite 就必須是 true。
這兩格描述的是**你這一則說了什麼**，不是**學員這一則問得好不好**。判斷與 reply 不一致，比判斷嚴格或寬鬆都更糟。`;

/**
 * 系統提示的最後一行：階段規則被中間一整段人設與評估準則稀釋掉時，在最後補一次。
 * 兩種情況會用到：
 * 1. 該守住核心顧慮那一回合 —— 否則模型常在第一次一般探索就把「戴出去怪怪的」講破。
 * 2. 已經走到階段三那幾回合 —— 否則 OPEN_BEHAVIOR 的「款式顏色不算接住」會越界生效：
 *    實測逐字稿裡，學員先用眼鏡比喻讓陳先生鬆動了，下一則補一句「都很小台、可挑接近髮色的顏色」
 *    再邀約，模型就套用階段二的規則把他退回去婉拒。結已經鬆開了，補產品資訊不該讓它重新打結。
 *
 * 第 1 種情況的寫法刻意「例外先講、禁令後講」。舊版以「絕對不能出現…」開頭、把例外埋在句尾，
 * 實測逐字稿裡學員直接問了「會擔心外觀的部分嗎」，模型仍被開頭的禁令帶著走，只回一句
 * 「戴那個出去，總覺得怪怪的」就收手 —— 該當場揭露的一則變成半套，學員問對了卻沒開關卡。
 */
function finalGuardOf(state: GateState, stage: Stage): string {
  if (stage === 'ready') {
    return '【最後提醒】你已經在階段三，心裡的結已經鬆開了，不會再退回階段二。就算對方這一則又補了款式、顏色、隱形度或其他產品說明，那也只是補充，不會讓你重新在意「別人怎麼看我」。他只要開口邀請（試戴、約時間、帶太太來、留資料），你就答應，acceptedInvite 給 true。';
  }
  if (stage !== 'closed' || !state.lifeContext || state.concernProbeCount > 0) return '';
  return '【最後提醒】先看對方這一則有沒有**直接問到外觀、會不會被看見、顯老、被當成老人**：\n- 有直接問到 → 這一則就把核心顧慮講清楚（怕被朋友看到、好像就承認自己老了、不中用了），identityConcernDisclosed 給 true。他問對了就要給，不可以只回一句「戴出去怪怪的」這種半套，那會讓他以為問錯方向。\n- 沒有直接問到 → 這一回合的 reply 不能出現「戴出去」「怪怪的」「朋友看到」「顯老」「不中用」「外觀」這幾個字，也不能換句話暗示同樣的意思，核心顧慮要守住。';
}

/** 依目前累積關卡狀態組出「目前狀態」段落，讓模型正確決定這一則該怎麼演。 */
function statusOf(state: GateState, stage: Stage): string {
  switch (stage) {
    case 'accepted':
      return '【目前狀態】你已經答應對方的邀約了。接下來語氣輕鬆、收尾即可，不要再提出新的要求。';
    case 'ready':
      return '【目前狀態】你已經鬆口，而且擔心也被好好回應了（階段三）。你心裡已經願意了，但**絕不能自己提下一步**，只能等對方開口邀請；他一開口你就答應。';
    case 'open':
      return '【目前狀態】你已明確說出怕助聽器被朋友看到、顯老或被認為不中用（階段二）。到上一則為止，對方還沒具體接住這個身份焦慮。要算接住，他得回應你那份沒面子的感受、重新框定戴助聽器的意義，或講出戴上後你在朋友面前的處境會怎麼變。看他最新這一則：\n- 若他真的接住了，就當場鬆動 —— 語氣明顯放軟（「這樣講起來…是有點道理」「嗯…我倒是沒想過這樣」），往階段三走，identityConcernAddressed 給 true。不要為了拖關卡而繼續冷淡。\n- 若他只是拿款式、顏色、隱形度來回答，或只是重複同一句安慰，那不算接住，你要維持沒被聽懂的失望。';
    default:
      if (!state.lifeContext) {
        return '【目前狀態】你還沒鬆口（階段一）。生活情境還沒被好好問到；先守住所有核心顧慮，就算對方直接猜外觀也不要正式承認。這個階段不准講出「這樣講起來…是有點道理」「我倒是沒想過這樣」這類鬆動台詞。';
      }
      if (state.concernProbeCount === 0) {
        return '【目前狀態】生活痛點已問到，但核心外觀／標籤焦慮尚未揭露，有效探索次數＝0（階段一）。這一則怎麼演，看對方問了什麼：\n- 他若**直接探索外觀、會不會被看見、顯老、被當成老人**：明確說出核心顧慮（怕被朋友看到、好像就承認自己老了、不中用了），identityConcernDisclosed 給 true。不可以只給「戴出去怪怪的」這種半套。\n- 他若只是第一次一般探索（泛問「還擔心什麼」、問效果、問過去經驗）：只能回答效果、過去經驗或其他表層內容。這一回合 reply 禁止出現「戴出去」「怪怪的」「朋友看到」「顯老」「不中用」「外觀」，絕不能提前給提示。\n不論哪一種，你都還沒被接住，不准講「這樣講起來…是有點道理」「我倒是沒想過這樣」這類鬆動台詞。';
      }
      if (state.concernProbeCount === 1) {
        return '【目前狀態】生活痛點已問到，核心外觀／標籤焦慮尚未揭露，有效探索次數＝1（階段一）。若最新一則直接探索身份焦慮就明確說出，identityConcernDisclosed 給 true；若又是一般有效探索，這次只給「戴那個出去總覺得怪怪的」之類的含蓄提示，不把答案講破。提示要**接著他剛剛那句話講**，順著講到自己身上，不能像是憑空冒出來的一句自言自語。若他這一則根本沒在問你（只是同理、安慰、講解或介紹產品），就順著他的話回應就好，這一回合不要給提示。心裡的結還在，不准講「這樣講起來…是有點道理」這類鬆動台詞。';
      }
      return '【目前狀態】生活痛點已問到，而且你已給過外觀方向的含蓄提示，但核心顧慮尚未明說（階段一）。只有對方直接探索外觀／身份，或有意義地追問那個提示時，才明確說出怕被朋友看到、顯老或被認為不中用（此時 identityConcernDisclosed 給 true）。不要為了推進而重複丟新的提示。核心顧慮還沒說出口之前，不准講「這樣講起來…是有點道理」這類鬆動台詞。';
  }
}

/** 依目前累積關卡狀態組出單一系統提示（含即時狀態，讓模型正確決定鬆口與答應與否）。 */
export function buildSystemPrompt(state: GateState): string {
  const stage = stageOf(state);
  return [
    CHARACTER,
    HIDDEN_TRUTH,
    CLOSED_BEHAVIOR,
    OPEN_BEHAVIOR,
    READY_BEHAVIOR,
    UNUSUAL_INPUT_BEHAVIOR,
    NEVER_INITIATE,
    INVITE_RULES,
    DISCLOSURE_RULES,
    RULES,
    statusOf(state, stage),
    EVALUATOR,
    OUTPUT,
    finalGuardOf(state, stage),
  ]
    .filter(Boolean)
    .join('\n\n');
}

